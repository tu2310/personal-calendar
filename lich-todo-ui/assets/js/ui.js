export function icon(name, extraClass = '') {
  const svg = ICONS[name] || ICONS['folder'];
  if (!extraClass) return svg.replace('<svg', '<svg class="icon"');
  return svg.replace('<svg', `<svg class="icon ${extraClass}"`);
}

// Date helpers
export function formatDateVN(dateStr) {
  if (!dateStr) return '';
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    return `${parts[2]}/${parts[1]}/${parts[0]}`;
  }
  return dateStr;
}

export function isDateToday(dateStr) {
  if (!dateStr) return false;
  const now = new Date();
  const yyyy = now.getFullYear();
  const mm = String(now.getMonth() + 1).padStart(2, '0');
  const dd = String(now.getDate()).padStart(2, '0');
  return dateStr === `${yyyy}-${mm}-${dd}`;
}

export function isDateOverdue(dateStr) {
  if (!dateStr) return false;
  const now = new Date();
  const yyyy = now.getFullYear();
  const mm = String(now.getMonth() + 1).padStart(2, '0');
  const dd = String(now.getDate()).padStart(2, '0');
  const todayStr = `${yyyy}-${mm}-${dd}`;
  return dateStr < todayStr;
}

// Toast System
export function showToast(message, actionLabel = null, onAction = null) {
  const container = document.getElementById('toast-container');
  if (!container) return;

  const toast = document.createElement('div');
  toast.className = 'toast';
  toast.setAttribute('role', 'status');
  toast.setAttribute('aria-live', 'polite');

  let actionHtml = '';
  if (actionLabel) {
    actionHtml = `<button type="button" class="toast-action">${actionLabel}</button>`;
  }

  toast.innerHTML = `<span>${message}</span>${actionHtml}`;
  container.appendChild(toast);

  if (actionLabel && onAction) {
    const btn = toast.querySelector('.toast-action');
    btn.addEventListener('click', () => {
      onAction();
      toast.remove();
    });
  }

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transition = 'opacity 200ms ease';
    setTimeout(() => toast.remove(), 250);
  }, 4000);
}

// Modal & Bottom Sheet Manager
let activeOpenerElement = null;

export function openModal(modalId, openerElement = null) {
  activeOpenerElement = openerElement || document.activeElement;
  const overlay = document.getElementById(modalId);
  if (!overlay) return;

  overlay.classList.add('active');
  overlay.setAttribute('aria-hidden', 'false');

  // Focus trap / initial focus on first focusable element
  setTimeout(() => {
    const focusable = overlay.querySelectorAll('button, input, select, textarea, [tabindex="0"]');
    if (focusable.length > 0) {
      focusable[0].focus();
    }
  }, 50);
}

export function closeModal(modalId) {
  const overlay = document.getElementById(modalId);
  if (!overlay) return;

  overlay.classList.remove('active');
  overlay.setAttribute('aria-hidden', 'true');

  if (activeOpenerElement && typeof activeOpenerElement.focus === 'function') {
    activeOpenerElement.focus();
    activeOpenerElement = null;
  }
}

